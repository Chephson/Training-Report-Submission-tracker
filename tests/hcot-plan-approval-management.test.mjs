import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const api=readFileSync('src/api.ts','utf8'),ui=readFileSync('public/static/app.js','utf8')
test('training plan approval is admin-only, requires participants, synchronizes into active reporting period',()=>{
 const route=api.slice(api.indexOf("api.patch('/hcot/plans/:id/approval'"),api.indexOf("api.get('/hcot/plans/:id/export'"))
 assert.match(route,/isHcotCompetencyAdmin/)
 assert.match(route,/defaultPeriod\(c.env.DB\)/)
 assert.match(route,/participants.results.length/)
 assert.match(route,/staff.active|p.active/)
 assert.match(route,/INSERT OR IGNORE INTO programme_assignments/)
 assert.match(route,/await c.env.DB.batch\(writes\)/)
 assert.match(route,/status='approved'/)
 assert.match(route,/already_approved:true/)
})
test('CSV export is restricted to admins and contains plan and participant details',()=>{
 const route=api.slice(api.indexOf("api.get('/hcot/plans/:id/export'"),api.indexOf("api.delete('/hcot/plans/:id'"))
 assert.match(route,/isHcotCompetencyAdmin/)
 assert.match(route,/text\/csv/)
 assert.match(route,/hcot_participants/)
 assert.match(ui,/hcot-export-plan/)
})
test('competency group edit/delete keeps library competencies intact',()=>{
 const route=api.slice(api.indexOf("api.patch('/hcot/competency-groups/:id'"),api.indexOf("api.post('/hcot/competency-groups/import'"))
 assert.match(route,/isHcotCompetencyAdmin/)
 assert.match(route,/DELETE FROM hcot_group_competencies/)
 assert.match(route,/DELETE FROM hcot_cadre_groups/)
 assert.match(route,/DELETE FROM hcot_cadre_group_scopes/)
 assert.doesNotMatch(route,/DELETE FROM hcot_competencies/)
 assert.match(ui,/hcg-save-group/)
 assert.match(ui,/hcg-delete-group/)
})
test('programme deletion preserves reports and allows approved plan history to remain',()=>{
 const route=api.slice(api.indexOf("api.delete('/programmes/:id'"),api.indexOf("api.post('/programme-assignments/import'"))
 assert.match(route,/isHcotCompetencyAdmin/)
 assert.match(route,/approved HCOT plans/)
 assert.match(route,/DELETE FROM programme_assignments/)
 assert.match(route,/DELETE FROM programmes/)
 assert.doesNotMatch(route,/DELETE FROM submissions/)
 assert.match(ui,/pg-delete/)
})
test('training plan UI has approval dropdown and export, not Calendar label',()=>{
 assert.match(ui,/Pending Approval/)
 assert.match(ui,/Approved/)
 assert.match(ui,/data-section="calendar">Training Plan/)
 assert.match(ui,/hcot-approval/)
 assert.match(ui,/\$\$\('\.hcot-approval'\)\.forEach/)
 assert.match(ui,/\$\$\('\.hcot-export-plan'\)\.forEach/)
})
